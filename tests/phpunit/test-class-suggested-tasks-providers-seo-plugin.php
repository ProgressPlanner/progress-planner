namespace Progress_Planner\Tests;

use Progress_Planner\Suggested_Tasks\Providers\SEO_Plugin;

/**
 * Suggested_Tasks_Providers_SEO_Plugin_Test test case.
 */
class Suggested_Tasks_Providers_SEO_Plugin_Test extends \WP_UnitTestCase {

	/**
	 * SEO_Plugin instance.
	 *
	 * @var SEO_Plugin
	 */
	protected $provider;

	/**
	 * Setup the test case.
	 *
	 * @return void
	 */
	public function setUp(): void {
		parent::setUp();
		$this->provider = new SEO_Plugin();
	}

	/**
	 * Test get_provider_id returns correct ID.
	 *
	 * @return void
	 */
	public function test_get_provider_id() {
		$this->assertEquals( 'seo-plugin', $this->provider->get_provider_id() );
	}

	/**
	 * Test should_add_task returns boolean.
	 *
	 * @return void
	 */
	public function test_should_add_task() {
		$result = $this->provider->should_add_task();
		$this->assertIsBool( $result );
	}
}
